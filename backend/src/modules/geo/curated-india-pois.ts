export function buildGoogleMapsPlaceUrl(lat: number, lng: number, label?: string): string {
  const query = label
    ? `${lat.toFixed(6)},${lng.toFixed(6)}`
    : `${lat.toFixed(6)},${lng.toFixed(6)}`;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

export function buildGoogleMapsDirectionsUrl(
  origin: { lat: number; lng: number },
  destination: { lat: number; lng: number },
  travelMode: 'driving' | 'walking' | 'transit' = 'driving'
): string {
  const o = `${origin.lat.toFixed(6)},${origin.lng.toFixed(6)}`;
  const d = `${destination.lat.toFixed(6)},${destination.lng.toFixed(6)}`;
  return `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(o)}&destination=${encodeURIComponent(d)}&travelmode=${travelMode}`;
}

