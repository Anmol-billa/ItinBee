export function buildGuestFallbackFromSample(shortId: string): GuestShareProjection | null {
  const ws = SAMPLE_WORKSPACES[shortId];
  if (!ws) return null;
  const { vaultBytesUsed: _u, vaultQuotaBytes: _q, ...tripRest } = ws.trip;
  const lines = [
    `*${ws.trip.title}* (${ws.trip.destinationSummary})`,
    ...ws.days.map((d) => {
      const dayStops = ws.items
        .filter((i) => i.dayId === d.id && !i.deletedAt)
        .sort((a, b) => a.sortKey.localeCompare(b.sortKey))
        .map((i) => `  • ${i.startTime ? `${i.startTime} — ` : ''}${i.title}`)
        .join('\n');
      return `\nDay ${d.dayNumber}: ${d.themeTitle}\n${dayStops || '  • Open schedule'}`;
    }),
    `\nLive map & polls: https://itinbee.com/t/${ws.trip.shortId}`,
  ];
  return {
    redactPii: true,
    trip: tripRest,
    plannerName: ws.members[0]?.displayName ?? 'Planner',
    days: ws.days,
    items: ws.items,
    shortlist: ws.shortlist,
    bookings: ws.bookings,
    polls: ws.polls,
    whatsappDigestText: lines.join('\n'),
  };
}
